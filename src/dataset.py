"""
src/dataset.py
==============
PyTorch Dataset and Albumentations augmentation pipelines for EdgeWeather.

Academic & Production Features:
  - Atmospheric-aware data augmentation (simulated fog, motion blur, color jitter).
  - Strict input validation with corrupted image handling.
  - Reproducible CSV-based split loading (generated by src/deduplicate.py).
  - Built-in synthetic dataset generator for offline unit tests and CI/CD pipelines.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, Callable, Sequence

import albumentations as A
from albumentations.pytorch import ToTensorV2
import numpy as np
import pandas as pd
from PIL import Image, ImageDraw
import torch
from torch.utils.data import DataLoader, Dataset

from src.utils import get_logger

logger = get_logger(__name__)

DEFAULT_CLASSES: list[str] = [
    "dew",
    "fog",
    "frost",
    "glaze",
    "hail",
    "lightning",
    "rain",
    "rainbow",
    "rime",
    "sandstorm",
    "snow",
]
IMAGENET_MEAN: tuple[float, float, float] = (0.485, 0.456, 0.406)
IMAGENET_STD: tuple[float, float, float] = (0.229, 0.224, 0.225)


# ── Augmentation Pipelines ───────────────────────────────────────────────────

def get_train_transforms(
    image_size: int = 224,
    mean: Sequence[float] = IMAGENET_MEAN,
    std: Sequence[float] = IMAGENET_STD,
    color_jitter_p: float = 0.5,
    blur_p: float = 0.3,
    shift_scale_rotate_p: float = 0.5,
) -> A.Compose:
    """Build the academic-grade training augmentation pipeline.

    Specifically chosen for outdoor weather classification:
      - RandomResizedCrop simulates scale invariance and zoom variations.
      - HorizontalFlip preserves atmospheric physical consistency.
      - ColorJitter simulates diurnal illumination and camera sensor shifts.
      - MotionBlur / GaussianBlur simulates vehicle vibration and atmospheric haze.
      - ShiftScaleRotate simulates camera mount angles on mobile / drone rigs.

    Args:
        image_size: Target square image dimension (e.g., 224).
        mean: Normalization channel means.
        std: Normalization channel standard deviations.
        color_jitter_p: Probability of applying color jitter.
        blur_p: Probability of applying motion/gaussian blur.
        shift_scale_rotate_p: Probability of applying affine transformations.

    Returns:
        Configured :class:`albumentations.Compose` transform pipeline.
    """
    return A.Compose(
        [
            A.RandomResizedCrop(
                size=(image_size, image_size),
                scale=(0.8, 1.0),
                p=1.0,
            ),
            A.HorizontalFlip(p=0.5),
            A.ColorJitter(
                brightness=0.2,
                contrast=0.2,
                saturation=0.2,
                hue=0.1,
                p=color_jitter_p,
            ),
            A.OneOf(
                [
                    A.MotionBlur(blur_limit=5, p=1.0),
                    A.GaussianBlur(blur_limit=(3, 5), p=1.0),
                ],
                p=blur_p,
            ),
            A.ShiftScaleRotate(
                shift_limit=0.0625,
                scale_limit=0.1,
                rotate_limit=15,
                border_mode=0,
                p=shift_scale_rotate_p,
            ),
            A.Normalize(mean=mean, std=std),
            ToTensorV2(),
        ]
    )


def get_eval_transforms(
    image_size: int = 224,
    mean: Sequence[float] = IMAGENET_MEAN,
    std: Sequence[float] = IMAGENET_STD,
) -> A.Compose:
    """Build deterministic validation / test evaluation pipeline.

    Standard ImageNet protocol:
      1. Resize to (image_size + 32)
      2. CenterCrop to (image_size, image_size)
      3. Normalize and convert to PyTorch tensor.

    Args:
        image_size: Target square evaluation dimension (e.g., 224).
        mean: Normalization channel means.
        std: Normalization channel standard deviations.

    Returns:
        Deterministic :class:`albumentations.Compose` pipeline.
    """
    resize_dim = int(image_size * 256 / 224)
    return A.Compose(
        [
            A.Resize(height=resize_dim, width=resize_dim),
            A.CenterCrop(height=image_size, width=image_size),
            A.Normalize(mean=mean, std=std),
            ToTensorV2(),
        ]
    )


# ── PyTorch Weather Dataset ──────────────────────────────────────────────────

class WeatherDataset(Dataset):
    """PyTorch Dataset for multi-class weather condition classification.

    Loads images referenced in a CSV split manifest (columns: ``filepath``, ``label``)
    or directly from a DataFrame / path list, applying Albumentations transformations.

    Attributes:
        df: Underlying DataFrame with image paths and labels.
        class_to_idx: Dictionary mapping class name to integer class ID.
        idx_to_class: Inverted mapping from integer ID to class name.
        transforms: Albumentations pipeline applied on loaded RGB images.
    """

    def __init__(
        self,
        data_source: str | Path | pd.DataFrame,
        class_names: Sequence[str] = DEFAULT_CLASSES,
        transforms: A.Compose | None = None,
        base_dir: str | Path | None = None,
    ) -> None:
        """Initialize the WeatherDataset.

        Args:
            data_source: Path to CSV split file, or an existing pandas DataFrame.
            class_names: Ordered list of unique class names.
            transforms: Albumentations Compose pipeline (default: eval transforms).
            base_dir: Optional base path to prepend if filepaths in CSV are relative.
        """
        super().__init__()
        self.class_names = list(class_names)
        self.class_to_idx: dict[str, int] = {c: i for i, c in enumerate(self.class_names)}
        self.idx_to_class: dict[int, str] = {i: c for c, i in self.class_to_idx.items()}
        self.transforms = transforms or get_eval_transforms()
        self.base_dir = Path(base_dir) if base_dir else None

        if isinstance(data_source, pd.DataFrame):
            self.df = data_source.copy().reset_index(drop=True)
        else:
            path = Path(data_source)
            if not path.exists():
                raise FileNotFoundError(f"Dataset manifest not found: {path}")
            self.df = pd.read_csv(path).reset_index(drop=True)

        # Normalize column names if using alternative conventions (e.g. path / class_name from deduplicate.py)
        col_rename = {}
        if "path" in self.df.columns and "filepath" not in self.df.columns:
            col_rename["path"] = "filepath"
        if "image_path" in self.df.columns and "filepath" not in self.df.columns:
            col_rename["image_path"] = "filepath"
        if "class_name" in self.df.columns and "label" not in self.df.columns:
            col_rename["class_name"] = "label"
        if "class" in self.df.columns and "label" not in self.df.columns:
            col_rename["class"] = "label"
        if col_rename:
            self.df = self.df.rename(columns=col_rename)

        if "filepath" not in self.df.columns or "label" not in self.df.columns:
            raise ValueError(
                f"Dataset manifest must contain 'filepath' (or 'path') and 'label' (or 'class_name') columns. Found: {list(self.df.columns)}"
            )

        # Filter out unknown classes if any
        initial_len = len(self.df)
        self.df = self.df[self.df["label"].isin(self.class_to_idx)].reset_index(drop=True)
        if len(self.df) < initial_len:
            logger.warning(
                "Filtered out %d rows with unrecognized class labels.",
                initial_len - len(self.df),
            )

        # Map labels to integer targets
        self.df["target"] = self.df["label"].map(self.class_to_idx)

    def __len__(self) -> int:
        return len(self.df)

    def __getitem__(self, idx: int) -> dict[str, Any]:
        """Fetch a single sample by integer index.

        Returns:
            Dictionary containing:
              - 'image': FloatTensor of shape (3, H, W)
              - 'label': torch.long scalar class target
              - 'label_name': String class name
              - 'filepath': Original string path to the image
        """
        row = self.df.iloc[idx]
        raw_path = Path(str(row["filepath"]))
        img_path = (self.base_dir / raw_path) if self.base_dir and not raw_path.is_absolute() else raw_path

        try:
            with Image.open(img_path) as img:
                img_rgb = np.array(img.convert("RGB"))
        except Exception as exc:
            logger.warning("Failed to load image %s (%s). Falling back to neutral canvas.", img_path, exc)
            img_rgb = np.zeros((224, 224, 3), dtype=np.uint8)

        if self.transforms is not None:
            augmented = self.transforms(image=img_rgb)
            image_tensor = augmented["image"]
        else:
            # Fallback simple tensor conversion
            image_tensor = torch.from_numpy(img_rgb.transpose(2, 0, 1)).float() / 255.0

        target = int(row["target"])
        return {
            "image": image_tensor,
            "label": torch.tensor(target, dtype=torch.long),
            "label_name": str(row["label"]),
            "filepath": str(img_path),
        }

    def get_class_distribution(self) -> dict[str, int]:
        """Return the count of images per class in this dataset split."""
        counts = self.df["label"].value_counts().to_dict()
        return {c: counts.get(c, 0) for c in self.class_names}


# ── DataLoader Factory ───────────────────────────────────────────────────────

def create_dataloaders(
    config: dict[str, Any],
    train_df_or_csv: str | Path | pd.DataFrame | None = None,
    val_df_or_csv: str | Path | pd.DataFrame | None = None,
    test_df_or_csv: str | Path | pd.DataFrame | None = None,
    data_dir: str | Path | None = None,
) -> dict[str, DataLoader]:
    """Instantiate reproducible PyTorch DataLoaders for train, val, and test splits.

    Args:
        config: Loaded project configuration dictionary (base_config + model_config).
        train_df_or_csv: Explicit path/DataFrame for train split.
        val_df_or_csv: Explicit path/DataFrame for val split.
        test_df_or_csv: Explicit path/DataFrame for test split.
        data_dir: Optional directory where default train.csv, val.csv, test.csv live.

    Returns:
        Dictionary mapping split name ('train', 'val', 'test') to :class:`DataLoader`.
    """
    dataset_cfg = config.get("dataset", {})
    dataloader_cfg = config.get("dataloader", {})
    aug_cfg = config.get("augmentation", {})

    classes = dataset_cfg.get("classes", DEFAULT_CLASSES)
    image_size = dataset_cfg.get("image_size", 224)
    batch_size = dataloader_cfg.get("batch_size", 32)
    # On Windows, PyTorch DataLoader spawn mode causes re-import loops and IPC delays.
    # Set safe default num_workers=0 on Windows unless explicitly forced.
    import sys
    if sys.platform == "win32" and not dataloader_cfg.get("force_multiprocessing", False):
        num_workers = 0
    else:
        num_workers = dataloader_cfg.get("num_workers", 2)
    pin_memory = dataloader_cfg.get("pin_memory", True) and torch.cuda.is_available()

    # Build transforms
    train_transform = get_train_transforms(
        image_size=image_size,
        mean=aug_cfg.get("mean", IMAGENET_MEAN),
        std=aug_cfg.get("std", IMAGENET_STD),
        color_jitter_p=aug_cfg.get("color_jitter", {}).get("p", 0.5),
        blur_p=aug_cfg.get("blur_p", 0.3),
        shift_scale_rotate_p=aug_cfg.get("shift_scale_rotate_p", 0.5),
    )
    eval_transform = get_eval_transforms(
        image_size=image_size,
        mean=aug_cfg.get("mean", IMAGENET_MEAN),
        std=aug_cfg.get("std", IMAGENET_STD),
    )

    # Determine split sources
    processed_dir = Path(data_dir or config.get("paths", {}).get("processed_dir", "data/processed"))
    train_src = train_df_or_csv or (processed_dir / "train.csv")
    val_src = val_df_or_csv or (processed_dir / "val.csv")
    test_src = test_df_or_csv or (processed_dir / "test.csv")

    loaders: dict[str, DataLoader] = {}

    if train_src and (isinstance(train_src, pd.DataFrame) or Path(train_src).exists()):
        train_ds = WeatherDataset(train_src, class_names=classes, transforms=train_transform)
        loaders["train"] = DataLoader(
            train_ds,
            batch_size=batch_size,
            shuffle=True,
            num_workers=num_workers,
            pin_memory=pin_memory,
            drop_last=True,
        )

    if val_src and (isinstance(val_src, pd.DataFrame) or Path(val_src).exists()):
        val_ds = WeatherDataset(val_src, class_names=classes, transforms=eval_transform)
        loaders["val"] = DataLoader(
            val_ds,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=pin_memory,
            drop_last=False,
        )

    if test_src and (isinstance(test_src, pd.DataFrame) or Path(test_src).exists()):
        test_ds = WeatherDataset(test_src, class_names=classes, transforms=eval_transform)
        loaders["test"] = DataLoader(
            test_ds,
            batch_size=batch_size,
            shuffle=False,
            num_workers=num_workers,
            pin_memory=pin_memory,
            drop_last=False,
        )

    return loaders


# ── Synthetic Dataset Generator (for CI/CD, tests & dry-runs) ────────────────

def create_synthetic_weather_dataset(
    output_dir: str | Path,
    num_samples_per_class: int = 15,
    image_size: tuple[int, int] = (224, 224),
    class_names: Sequence[str] = DEFAULT_CLASSES,
) -> dict[str, Path]:
    """Generate a lightweight synthetic multi-class weather dataset for tests and CI.

    Creates realistic visual patterns representing each weather class (e.g.,
    overcast grey gradients for cloudy, blue-tinted linear streaks for rain,
    golden solar glow for shine, warm radial gradient for sunrise, white ground
    for snow, hazy low-contrast noise for fog).

    Args:
        output_dir: Root directory to save the synthetic dataset.
        num_samples_per_class: Number of sample images per class.
        image_size: Dimensions of generated sample images.
        class_names: List of target weather classes.

    Returns:
        Dictionary mapping split names ('train', 'val', 'test') to generated CSV manifests.
    """
    output_path = Path(output_dir)
    images_dir = output_path / "images"
    images_dir.mkdir(parents=True, exist_ok=True)

    records: list[dict[str, str]] = []

    # Distinct colour palettes for atmospheric visual cues
    weather_palettes: dict[str, tuple[int, int, int]] = {
        "cloudy": (120, 130, 140),
        "rain": (40, 70, 110),
        "shine": (240, 220, 100),
        "sunrise": (230, 110, 60),
        "snow": (235, 240, 248),
        "fog": (180, 185, 190),
    }

    w, h = image_size
    for class_name in class_names:
        base_color = weather_palettes.get(class_name, (128, 128, 128))
        for idx in range(num_samples_per_class):
            img = Image.new("RGB", (w, h), color=base_color)
            draw = ImageDraw.Draw(img)

            # Add class-specific procedural visual artifacts
            if class_name == "rain":
                # Simulated raindrops
                for _ in range(30):
                    x0 = np.random.randint(0, w)
                    y0 = np.random.randint(0, h - 20)
                    draw.line([(x0, y0), (x0 + 4, y0 + 16)], fill=(200, 220, 255), width=1)
            elif class_name == "shine":
                # Simulated sun glare disk
                draw.ellipse([(w // 4, h // 4), (3 * w // 4, 3 * h // 4)], fill=(255, 255, 180))
            elif class_name == "sunrise":
                # Simulated golden horizon
                draw.rectangle([(0, h // 2), (w, h)], fill=(200, 60, 40))
            elif class_name == "snow":
                # Simulated snowflakes
                for _ in range(40):
                    x = np.random.randint(0, w)
                    y = np.random.randint(0, h)
                    draw.ellipse([(x, y), (x + 3, y + 3)], fill=(255, 255, 255))
            elif class_name == "fog":
                # Simulated low-contrast hazy overlay
                noise = np.random.randint(-15, 15, (h, w, 3), dtype=np.int16)
                arr = np.clip(np.array(img, dtype=np.int16) + noise, 0, 255).astype(np.uint8)
                img = Image.fromarray(arr)

            filename = f"{class_name}_{idx:03d}.jpg"
            file_path = images_dir / filename
            img.save(file_path, "JPEG", quality=90)

            records.append({
                "filepath": str(file_path.resolve()),
                "label": class_name,
            })

    full_df = pd.DataFrame(records).sample(frac=1.0, random_state=42).reset_index(drop=True)

    # Stratified split: 70% train, 15% val, 15% test
    train_dfs: list[pd.DataFrame] = []
    val_dfs: list[pd.DataFrame] = []
    test_dfs: list[pd.DataFrame] = []

    for _, group in full_df.groupby("label"):
        n = len(group)
        n_train = max(1, int(0.70 * n))
        n_val = max(1, int(0.15 * n))
        train_dfs.append(group.iloc[:n_train])
        val_dfs.append(group.iloc[n_train : n_train + n_val])
        test_dfs.append(group.iloc[n_train + n_val :])

    train_df = pd.concat(train_dfs).sample(frac=1.0, random_state=42).reset_index(drop=True)
    val_df = pd.concat(val_dfs).sample(frac=1.0, random_state=42).reset_index(drop=True)
    test_df = pd.concat(test_dfs).sample(frac=1.0, random_state=42).reset_index(drop=True)

    train_csv = output_path / "train.csv"
    val_csv = output_path / "val.csv"
    test_csv = output_path / "test.csv"

    train_df.to_csv(train_csv, index=False)
    val_df.to_csv(val_csv, index=False)
    test_df.to_csv(test_csv, index=False)

    logger.info("Generated synthetic dataset at %s with %d samples.", output_path, len(full_df))
    return {
        "train": train_csv,
        "val": val_csv,
        "test": test_csv,
    }
